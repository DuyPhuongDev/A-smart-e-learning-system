  /**
   * Step 1: Student-level imputation (reduced).
   * Missing GPA fields default to 0.
   */
  private void imputeStudentLevel(List<RawFeatureRow> rows) {
    // Group by student to ensure no cross-student data leakage
    Map<UUID, List<RawFeatureRow>> byStudent = rows.stream().collect(Collectors.groupingBy(r -> r.row.studentId()));

    for (List<RawFeatureRow> studentRows : byStudent.values()) {
      // Sort each student's rows by semKey for temporal ordering
      studentRows.sort(Comparator.comparingInt(r -> r.row.semKey()));

      for (RawFeatureRow raw : studentRows) {
        boolean needsImpute = raw.history.numSemestersPrior() <= 0 || raw.history.cumulativeGradeAvg() == null;

        if (needsImpute) {
          raw.imputedCumulativeGradeAvg = 0.0;
          raw.imputedPreviousSemGradeAvg = 0.0;
        } else {
          raw.imputedCumulativeGradeAvg = orDefault(raw.history.cumulativeGradeAvg());
          raw.imputedPreviousSemGradeAvg = orDefault(raw.history.previousSemGradeAvg());
        }
      }
    }
  }

  /**
   * Step 2: Finalize other features (reduced).
   * relative_avg_course_grade defaults to previous semester GPA or 0 when missing.
   */
  private void imputeFinalize(List<RawFeatureRow> rows) {
    for (RawFeatureRow raw : rows) {
      if (!raw.relative.hasRelative()) {
        raw.imputedRelativeAvg = raw.imputedPreviousSemGradeAvg != null ? raw.imputedPreviousSemGradeAvg : 0.0;
      } else {
        raw.imputedRelativeAvg = orDefault(raw.relative.relativeAvg());
      }

      raw.imputedCumulativeGradeAvg = orDefault(raw.imputedCumulativeGradeAvg);
      raw.imputedPreviousSemGradeAvg = orDefault(raw.imputedPreviousSemGradeAvg);
    }
  }

  private GradePredictionDataset buildEntity(RawFeatureRow raw, UUID versionId) {
    EnrichedEnrollment row = raw.row;

    return GradePredictionDataset.builder()
        .studentId(row.studentId())
        .semesterId(row.semesterId())
        .subjectId(row.subjectId())
        .versionId(versionId)
        .courseGrade(row.courseGrade4pt())
        .semCredits(raw.semCredits)
        .semCreditsSquared(raw.semCredits * raw.semCredits)
        .retakeNo(row.attemptIndex())
        .numSemestersPrior(raw.history.numSemestersPrior())
        .cumulativeGradeAvg(raw.imputedCumulativeGradeAvg)
        .previousSemGradeAvg(raw.imputedPreviousSemGradeAvg)
        .subjectHistMedianSmooth(raw.baseline.histMedianSmooth())
        .relativeAvgCourseGrade(raw.imputedRelativeAvg)
        .build();
  }

  /**
   * Checks if a row has ALL features computed from real data (no imputation needed).
   * Records with any imputed features are filtered out of the dataset.
   */
  private boolean hasCompleteData(RawFeatureRow raw) {
    // Student history must have real data (student has prior semesters)
    boolean hasStudentHistory =
        raw.history.numSemestersPrior() > 0 && raw.history.cumulativeGradeAvg() != null && raw.history.previousSemGradeAvg() != null;

    // Course baseline must have real historical data (not fallback)
    boolean hasCourseHistory = !raw.baseline.histMissing() && !raw.baseline.isFallback();

    return hasStudentHistory && hasCourseHistory;
  }

  private void upsertBatch(List<GradePredictionDataset> entities, UUID versionId) {
    for (int i = 0; i < entities.size(); i += BATCH_SIZE) {
      int end = Math.min(i + BATCH_SIZE, entities.size());
      List<GradePredictionDataset> batch = entities.subList(i, end);

      // Extract fields into arrays for PostgreSQL unnest
      String[] studentIds = batch.stream().map(e -> e.getStudentId().toString()).toArray(String[]::new);
      String[] semesterIds = batch.stream().map(e -> e.getSemesterId().toString()).toArray(String[]::new);
      String[] subjectIds = batch.stream().map(e -> e.getSubjectId().toString()).toArray(String[]::new);

      Double[] courseGrades = batch.stream().map(GradePredictionDataset::getCourseGrade).toArray(Double[]::new);
      Integer[] semCredits = batch.stream().map(GradePredictionDataset::getSemCredits).toArray(Integer[]::new);
      Integer[] semCreditsSq = batch.stream().map(GradePredictionDataset::getSemCreditsSquared).toArray(Integer[]::new);
      Integer[] retakeNos = batch.stream().map(GradePredictionDataset::getRetakeNo).toArray(Integer[]::new);
      Integer[] numSems = batch.stream().map(GradePredictionDataset::getNumSemestersPrior).toArray(Integer[]::new);
      Double[] cumGrades = batch.stream().map(GradePredictionDataset::getCumulativeGradeAvg).toArray(Double[]::new);
      Double[] prevSemGrades = batch.stream()
          .map(GradePredictionDataset::getPreviousSemGradeAvg)
          .toArray(Double[]::new);
      Double[] histMedians = batch.stream()
          .map(GradePredictionDataset::getSubjectHistMedianSmooth)
          .toArray(Double[]::new);
      Double[] relAvgs = batch.stream().map(GradePredictionDataset::getRelativeAvgCourseGrade).toArray(Double[]::new);

      // TRUE batch upsert: single round trip for entire batch using PostgreSQL unnest
      datasetRepository.batchUpsert(
          versionId, studentIds, semesterIds, subjectIds, courseGrades, semCredits, semCreditsSq, retakeNos, numSems,
          cumGrades, prevSemGrades, histMedians, relAvgs);

      log.debug("Executed true batch upsert for {}/{} records", end, entities.size());
    }
  }

  private String compositeKey(UUID a, UUID b) {
    return a + "|" + b;
  }

  private static double orDefault(Double value) {
    return value != null ? value : 0.0;
  }

  private record EnrichedEnrollment(UUID studentId, UUID classId, UUID subjectId, UUID semesterId, int semKey,
                                    int credits, double finalGrade10pt, double courseGrade4pt, int attemptIndex,
                                    UUID curriculumSectionId) {
  }

  private record StudentHistory(int numSemestersPrior, Double cumulativeGradeAvg, Double previousSemGradeAvg) {
    static StudentHistory empty() {
      return new StudentHistory(0, null, null);
    }
  }

  private record CourseBaseline(int histCount, double histMedianSmooth, boolean histMissing, boolean isFallback) {
  }

  private record RelativeCourseResult(boolean hasRelative, Double relativeAvg) {
  }

  /**
   * Mutable container holding raw features + imputed values for one row.
   * Fields are filled in phases: Phase 7 (raw), then Phase 8 (imputation steps 1-4).
   */
  private static class RawFeatureRow {
    final EnrichedEnrollment row;
    final StudentHistory history;
    final CourseBaseline baseline;
    final RelativeCourseResult relative;
    final int semCredits;

    // Imputed student-level (Step 1)
    Double imputedCumulativeGradeAvg;
    Double imputedPreviousSemGradeAvg;

    // Imputed relative (Step 4)
    double imputedRelativeAvg;

    RawFeatureRow(
        EnrichedEnrollment row, StudentHistory history, CourseBaseline baseline,
        RelativeCourseResult relative, int semCredits) {
      this.row = row;
      this.history = history;
      this.baseline = baseline;
      this.relative = relative;
      this.semCredits = semCredits;
    }
  }
